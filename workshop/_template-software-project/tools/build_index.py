from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GEN = "<!-- GENERATED by tools/build_index.py - do not edit by hand -->"


def read(rel):
    return (ROOT / rel).read_text(encoding="utf-8")


def _read_optional(rel):
    """Like read(), but returns '' when the file does not exist yet -
    for registers a young project may not have created (robustness
    contract: a missing register leaves its section empty, never a crash)."""
    path = ROOT / rel
    return path.read_text(encoding="utf-8") if path.exists() else ""


def short(text, n=140):
    text = re.sub(r"\s+", " ", text).strip()
    return text if len(text) <= n else text[: n - 1].rstrip() + "…"


# excerpt cap for graph.json node bodies (entry text, whitespace-normalized)
EXCERPT_MAX = 800


# ---------------------------------------------------------------- parsers

def parse_requirements():
    path = ROOT / "01-requirements/requirements.md"
    if not path.exists():
        return []
    reqs = []
    for m in re.finditer(r"^\| (REQ-0*[1-9]\d*) \|([^|]+)\|([^|]+)\| ([^|]+) \|$",
                         path.read_text(encoding="utf-8"), re.M):
        rid, statement, criteria, prio = m.groups()
        reqs.append({
            "id": rid,
            "title": short(statement),
            # entry body = full statement + acceptance-criteria cell
            "excerpt": short(statement.strip() + " " + criteria.strip(),
                             EXCERPT_MAX),
            "prio": prio.strip().split()[0].rstrip("*"),
        })
    return reqs


def parse_decisions():
    path = ROOT / "DECISIONS.md"
    if not path.exists():
        return []
    text = path.read_text(encoding="utf-8")
    markers = {m.group(1): {"status": m.group(2).strip(),
                            "links": m.group(3).strip()}
               for m in re.finditer(
                   r"<!-- (DEC-0*[1-9]\d*) \| ([^|]+) \| links: ([^>]*)-->", text)}
    decs = []
    for m in re.finditer(r"(?ms)^## \[(DEC-0*[1-9]\d*)\] (\d{4}-\d{2}-\d{2}) - (.+?)$"
                         r"(.*?)(?=^## \[DEC-|\Z)", text):
        did, date, title, body = m.groups()
        info = markers.get(did, {"status": "?", "links": ""})
        # entry body = the record's bullets; the machine-readable marker
        # comment line and the Supersedes:/Amends: relation markers are
        # metadata, not text
        body = re.sub(r"(?m)^\s*<!--.*?-->\s*$", "", body)
        body = re.sub(r"(?im)^-\s*(?:Supersedes|Amends):[^\n]*$", "", body)
        decs.append({"id": did, "date": date, "title": short(title.strip(), 180),
                     "excerpt": short(body, EXCERPT_MAX),
                     "status": info["status"], "links": info["links"]})
    missing = [d["id"] for d in decs if d["id"] not in markers]
    if missing:
        print(f"WARN: DECs without marker: {', '.join(missing)}", file=sys.stderr)
    return decs


def parse_open_questions():
    oqs = []
    path = ROOT / "OPEN-QUESTIONS.md"
    if not path.exists():
        return oqs
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.startswith("| OQ-"):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 3 or not re.fullmatch(r"OQ-0*[1-9]\d*", cells[0]):
            continue
        # robust against literal pipes inside cells: id = first, question = second,
        # status = last cell
        mid = " | ".join(c for c in cells[2:-2] if c)
        oqs.append({"id": cells[0],
                    "title": short(cells[1]),
                    # entry body = question + resolve-by/answer cell(s)
                    "excerpt": short(cells[1] + (" | Resolve by: " + mid
                                                 if mid else ""), EXCERPT_MAX),
                    "status": cells[-1].replace("*", "").strip()})
    return oqs


def parse_risks():
    risks = []
    path = ROOT / "RISKS.md"
    if not path.exists():
        return risks
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.startswith("| RISK-"):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 3 or not re.fullmatch(r"RISK-0*[1-9]\d*", cells[0]):
            continue
        # description + mitigation (third cell from the right; robust from
        # the right against literal pipes in the description)
        body = cells[1] + (" Mitigation: " + cells[-3] if len(cells) >= 6 else "")
        risks.append({"id": cells[0],
                      "title": short(cells[1]),
                      "excerpt": short(body, EXCERPT_MAX),
                      "status": cells[-1].replace("*", "").strip()})
    return risks


def parse_changelog():
    chgs = []
    for m in re.finditer(r"(?ms)^## \[(CHG-0*[1-9]\d*[a-z]?)\] (\d{4}-\d{2}-\d{2}) - "
                         r"(.+?)$(.*?)(?=^## |\Z)", _read_optional("CHANGELOG.md")):
        chgs.append({"id": m.group(1), "date": m.group(2),
                     "title": short(m.group(3).strip(), 180),
                     # entry body = the entry's bullet block (Reason, Change, ...)
                     "excerpt": short(m.group(4), EXCERPT_MAX)})
    return chgs


def expand_reqs(cell):
    """'REQ-001..008' / 'REQ-010, 082' / 'REQ-088..090' / 'REQ-014, 083..087' -> list."""
    out = []
    for m in re.finditer(r"REQ-(\d{3})\.\.(\d{3})", cell):
        out += [f"REQ-{i:03d}" for i in range(int(m.group(1)), int(m.group(2)) + 1)]
    cell = re.sub(r"REQ-\d{3}\.\.\d{3}", "", cell)
    # continuation ranges without the REQ prefix, e.g. ", 083..087"
    for m in re.finditer(r"(?:^|,)\s*(\d{3})\.\.(\d{3})", cell):
        out += [f"REQ-{i:03d}" for i in range(int(m.group(1)), int(m.group(2)) + 1)]
    cell = re.sub(r"(?:^|,)\s*\d{3}\.\.\d{3}", "", cell)
    nums = []
    for part in cell.split(","):
        nums += re.findall(r"\d{3}", part)
    out += [f"REQ-{n}" for n in nums]
    seen, res = set(), []
    for r in out:
        if r not in seen:
            seen.add(r)
            res.append(r)
    return res


def parse_coverage():
    """solution-concept.md section 4 table -> {REQ-###: 'SC 3.x/3.y'}

    Returns {} when the file or the section does not exist yet
    (pre-phase-02), so the coverage column stays empty instead of
    failing the build."""
    path = ROOT / "02-solution-concept/solution-concept.md"
    if not path.exists():
        return {}
    text = path.read_text(encoding="utf-8")
    parts = text.split("## 4. Requirements coverage", 1)
    if len(parts) < 2:
        return {}
    sec = parts[1].split("\n## ", 1)[0]
    cov = {}
    for m in re.finditer(r"^\| (REQ-[^|]+) \| ([^|]+) \|$", sec, re.M):
        reqs, target = m.group(1), m.group(2)
        sections = re.findall(r"\d\.\d+", target)
        if not sections:
            continue
        ref = "SC " + "/".join(sections)
        for rid in expand_reqs(reqs):
            cov[rid] = ref
    return cov


def parse_allocations():
    """architecture.md allocation table -> {REQ-###: {'sub': [...], 'if': [...]}}

    Returns {} when the file or the table does not exist yet (pre-phase-04),
    so the ARC/IF and SUB columns stay empty instead of failing the build.
    """
    path = ROOT / "04-architecture/architecture.md"
    if not path.exists():
        return {}
    text = path.read_text(encoding="utf-8")
    # first heading whose text contains "allocation" (any level, any exact name)
    head = re.search(r"^#{1,6}\s+.*allocation.*$", text, re.M | re.I)
    if not head:
        return {}
    sec = text[head.end():]
    nxt = re.search(r"^#{1,6}\s", sec, re.M)
    if nxt:
        sec = sec[:nxt.start()]
    alloc = {}
    for line in sec.splitlines():
        if not line.lstrip().startswith("|"):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) != 3:
            continue
        rid, sub, iff = cells
        # header, separator and malformed rows are skipped, never fatal
        if not re.fullmatch(r"REQ-\d{3}", rid):
            continue
        if not re.fullmatch(r"SUB-\d{3}", sub):
            continue
        if iff != "-" and not re.fullmatch(r"IF-\d{3}", iff):
            continue
        entry = alloc.setdefault(rid, {"sub": [], "if": []})
        if sub not in entry["sub"]:
            entry["sub"].append(sub)
        if iff != "-" and iff not in entry["if"]:
            entry["if"].append(iff)
    return alloc


def parse_tc_allocations():
    """test-cases.md TC allocation table -> [{'tc', 'req', 'sub', 'if'}, ...]

    Returns [] when the file or the table does not exist yet (pre-phase-05),
    so the TC column stays empty instead of failing the build.
    """
    path = ROOT / "05-module-specification/test-cases.md"
    if not path.exists():
        return []
    text = path.read_text(encoding="utf-8")
    # first heading whose text contains "tc allocation" (any level, any name)
    head = re.search(r"^#{1,6}\s+.*tc allocation.*$", text, re.M | re.I)
    if not head:
        return []
    sec = text[head.end():]
    nxt = re.search(r"^#{1,6}\s", sec, re.M)
    if nxt:
        sec = sec[:nxt.start()]
    rows = []
    for line in sec.splitlines():
        if not line.lstrip().startswith("|"):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) != 4:
            continue
        tc, rid, sub, iff = cells
        # header, separator and malformed rows are skipped, never fatal
        if not re.fullmatch(r"TC-\d{3}", tc):
            continue
        if not re.fullmatch(r"REQ-\d{3}", rid):
            continue
        if not re.fullmatch(r"SUB-\d{3}", sub):
            continue
        if iff != "-" and not re.fullmatch(r"IF-\d{3}", iff):
            continue
        rows.append({"tc": tc, "req": rid, "sub": sub, "if": iff})
    return rows


def parse_if_register():
    """architecture.md section 3 -> {'ifs': [IF-###...], 'pinned': [IF-###...],
    'excerpts': {IF-###: entry body}}

    Returns {'ifs': [], 'pinned': [], 'excerpts': {}} when the file or section
    does not exist (pre-phase-04), so the coverage lines show a note instead of
    failing the build.
    """
    path = ROOT / "04-architecture/architecture.md"
    result = {"ifs": [], "pinned": [], "excerpts": {}}
    if not path.exists():
        return result
    text = path.read_text(encoding="utf-8")
    head = re.search(r"^## 3\. Interface register.*$", text, re.M)
    if not head:
        return result
    sec = text[head.end():]
    nxt = re.search(r"^## \d", sec, re.M)
    if nxt:
        sec = sec[: nxt.start()]
    for m in re.finditer(r"(?ms)^### (IF-\d{3}) - (.+?)$(.*?)(?=^### |\Z)", sec):
        iid, title, body = m.group(1), m.group(2), m.group(3)
        result["ifs"].append(iid)
        result["excerpts"][iid] = short(body, EXCERPT_MAX)
        if re.search(r"\(post-(R1|MVP) boundary\)", title):
            result["pinned"].append(iid)
    return result


def parse_sub_excerpts():
    """architecture.md section 2 submodule register -> {SUB-###: entry body}.

    Returns {} when the file or section does not exist yet (pre-phase-04)."""
    path = ROOT / "04-architecture/architecture.md"
    if not path.exists():
        return {}
    text = path.read_text(encoding="utf-8")
    head = re.search(r"^## \d+\. Submodule register.*$", text, re.M | re.I)
    if not head:
        return {}
    sec = text[head.end():]
    nxt = re.search(r"^## \d", sec, re.M)
    if nxt:
        sec = sec[: nxt.start()]
    out = {}
    for m in re.finditer(r"(?ms)^### (SUB-\d{3}) - .+?$(.*?)(?=^### |\Z)", sec):
        out[m.group(1)] = short(m.group(2), EXCERPT_MAX)
    return out


def parse_tc_register():
    """test-cases.md TC register table -> {TC-###: scenario cell}.

    Returns {} when the file or the table does not exist yet (pre-phase-05).
    The scenario (last cell) is the entry body; the TC allocation table parsed
    by parse_tc_allocations carries IDs only."""
    path = ROOT / "05-module-specification/test-cases.md"
    if not path.exists():
        return {}
    text = path.read_text(encoding="utf-8")
    head = re.search(r"^#{1,6}\s+.*tc register.*$", text, re.M | re.I)
    if not head:
        return {}
    sec = text[head.end():]
    nxt = re.search(r"^#{1,6}\s", sec, re.M)
    if nxt:
        sec = sec[: nxt.start()]
    out = {}
    for line in sec.splitlines():
        if not line.lstrip().startswith("|"):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) != 3:
            continue
        if not re.fullmatch(r"TC-\d{3}", cells[0]):
            continue
        out.setdefault(cells[0], short(cells[-1], EXCERPT_MAX))
    return out


def parse_fr_excerpts():
    """product/FEATURE-REQUESTS.md register -> {FR-###: entry body}.

    Returns {} when the file or the Register section does not exist. The
    template's literal 'FR-###' placeholder never matches \\d{3}."""
    path = ROOT / "product/FEATURE-REQUESTS.md"
    if not path.exists():
        return {}
    text = path.read_text(encoding="utf-8")
    head = re.search(r"^## Register.*$", text, re.M)
    sec = text[head.end():] if head else text
    out = {}
    for m in re.finditer(r"(?ms)^### (FR-\d{3}) - .+?$(.*?)(?=^### |^## |\Z)",
                         sec):
        out[m.group(1)] = short(m.group(2), EXCERPT_MAX)
    return out


def parse_agenda_item_excerpts():
    """decision-meetings/*.md -> {M-###: entry body}.

    Meeting files carry '## M-### - <title>' verdict records, agenda.md carries
    '### M-### - <title> [decided ...]' proposal records. Files are scanned in
    sorted order (meeting files sort before agenda.md) and the first occurrence
    wins, so a meeting verdict body beats the agenda proposal body."""
    out = {}
    d = ROOT / "decision-meetings"
    if not d.exists():
        return out
    for path in sorted(d.glob("*.md")):
        text = path.read_text(encoding="utf-8")
        for m in re.finditer(r"(?ms)^#{2,3} (M-\d{3}) - .+?$(.*?)(?=^#{2,3} |\Z)",
                             text):
            out.setdefault(m.group(1), short(m.group(2), EXCERPT_MAX))
    return out


def scan_if_test_markers():
    """IF-### tokens in test sources (src/tests/**/*.py, frontend/tests/**/*.ts)."""
    found = set()
    for pattern in ("src/tests/**/*.py", "frontend/tests/**/*.ts"):
        for path in sorted(ROOT.glob(pattern)):
            if "__pycache__" in path.parts:
                continue
            found |= set(re.findall(r"IF-\d{3}",
                                    path.read_text(encoding="utf-8")))
    return found


