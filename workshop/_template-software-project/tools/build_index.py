# CHANGELOG "Affected artifacts" lines (CHG-135).

ID_TOKEN = re.compile(
    r"\b(?:REQ|DEC|OQ|RISK|CHG|TC|SUB|IF|ARC|FR|M|D)-\d{1,3}[a-z]?\b")

PREFIX_TYPE = {"REQ": "requirement", "DEC": "decision", "OQ": "question",
               "RISK": "risk", "CHG": "change", "TC": "test-case",
               "SUB": "submodule", "IF": "interface", "ARC": "architecture",
               "FR": "feature-request", "M": "agenda-item", "D": "directive"}

# prefixes that live in parsed registers; edges to unknown ones are validator
# warnings (typo detector). Other prefixes get implicit nodes, no warning.
REGISTER_PREFIXES = ("REQ", "DEC", "OQ", "RISK", "CHG", "TC", "SUB", "IF")


def extract_ids(text):
    """Machine-readable ID tokens, expanding ranges (DEC-025..031, FR-001..007)
    and slash shorthand (REQ-021/053/058). Order-preserving, deduped."""
    ids = []

    def add(tok):
        if tok not in ids:
            ids.append(tok)

    for m in re.finditer(r"\b([A-Z]{2,4})-(\d{3})\.\.(?:[A-Z]{2,4}-)?(\d{3})\b",
                         text):
        prefix, a, b = m.group(1), int(m.group(2)), int(m.group(3))
        if 0 <= b - a <= 50:
            for i in range(a, b + 1):
                add(f"{prefix}-{i:03d}")
    text = re.sub(r"\b[A-Z]{2,4}-\d{3}\.\.(?:[A-Z]{2,4}-)?\d{3}\b", " ", text)
    for m in re.finditer(r"\b([A-Z]{2,4})-(\d{3})((?:/\d{3})+)", text):
        prefix = m.group(1)
        add(f"{prefix}-{m.group(2)}")
        for n in re.findall(r"\d{3}", m.group(3)):
            add(f"{prefix}-{n}")
    text = re.sub(r"\b[A-Z]{2,4}-\d{3}(?:/\d{3})+", " ", text)
    for tok in ID_TOKEN.findall(text):
        add(tok)
    return ids


def parse_oq_resolutions():
    """OPEN-QUESTIONS.md -> {OQ-###: [DEC-###...]} for resolved questions.

    The DEC reference sits in the 'Resolve by' cell (third column); because
    literal pipes inside the question cell can shift columns, all cells between
    question and the last two (Affects, Status) are scanned. Only rows whose
    status cell says resolved contribute 'closes' edges.
    """
    out = {}
    for line in _read_optional("OPEN-QUESTIONS.md").splitlines():
        if not line.startswith("| OQ-"):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 3 or not re.fullmatch(r"OQ-0*[1-9]\d*", cells[0]):
            continue
        if "resolved" not in cells[-1].lower():
            continue
        mid = " | ".join(cells[2:-2])
        decs = sorted(set(re.findall(r"DEC-\d{3}", mid)))
        if decs:
            out[cells[0]] = decs
    return out


def parse_dec_body_relations():
    """DECISIONS.md -> {DEC-###: {'amends': [...], 'supersedes': [...]}}.
    Primary source is the explicit machine-readable marker line
    `- Supersedes: DEC-###[, DEC-### ...]` (and the `- Amends:` analogue),
    anchored 2026-09-13 (owner decision, methods chat). Prose harvesting
    ('amends DEC-###', 'DEC-### superseded by this DEC') stays as the legacy
    fallback for pre-convention entries; it is conservative by design (option-
    menu phrasing like 'superseded versions retained' carries no DEC id).
    The marker `links:` list carries no relation type, so only these explicit
    relations upgrade a DEC->DEC edge from the generic 'links'."""
    out = {}
    for m in re.finditer(r"(?ms)^## \[(DEC-\d{3})\].*?$(.*?)(?=^## \[DEC-|\Z)",
                         read("DECISIONS.md")):
        did, body = m.group(1), m.group(2)
        rel = {"amends": set(), "supersedes": set()}
        for mm in re.finditer(r"(?im)^-\s*(Supersedes|Amends):\s*([^\n()]*)",
                              body):
            kind = "supersedes" if mm.group(1).lower() == "supersedes" else "amends"
            rel[kind].update(re.findall(r"DEC-\d{3}", mm.group(2)))
        for mm in re.finditer(r"(?i)\b(amend(?:s|ing)?|supersedes?)\s+(?:of\s+|to\s+)?(DEC-\d{3})",
                              body):
            rel["amends" if mm.group(1).lower().startswith("amend")
                else "supersedes"].add(mm.group(2))
        for mm in re.finditer(r"(?i)(DEC-\d{3})[^.\n]{0,60}?\b(superseded|amended) by this DEC\b",
                              body):
            rel["supersedes" if mm.group(2) == "superseded"
                else "amends"].add(mm.group(1))
        if rel["amends"] or rel["supersedes"]:
            out[did] = {k: sorted(v) for k, v in rel.items() if v}
    return out


def parse_chg_affects():
    """CHANGELOG.md -> {CHG-###: [ID...]} from each entry's 'Affected artifacts'
    block (the bullet plus its wrapped continuation lines). Wrapped lines are
    re-joined without a space after a trailing '/' or '-' so mid-token wraps
    stay machine-readable."""
    out = {}
    for sec in re.split(r"(?m)^## ", _read_optional("CHANGELOG.md")):
        m = re.match(r"\[(CHG-0*[1-9]\d*[a-z]?)\]", sec)
        if not m:
            continue
        cid = m.group(1)
        bm = re.search(r"(?ms)^- Affected artifacts:\s*(.*?)(?=^- [A-Z]|\Z)", sec)
        if not bm:
            continue
        joined = ""
        for ln in (l.strip() for l in bm.group(1).splitlines() if l.strip()):
            if joined.endswith(("/", "-")):
                joined += ln
            else:
                joined += (" " if joined else "") + ln
        bucket = out.setdefault(cid, [])
        for tok in extract_ids(joined):
            if tok != cid and tok not in bucket:
                bucket.append(tok)
    return out


def parse_releases():
    """RELEASES.md -> {'releases': [{'id', 'title'}], 'edges': {REQ-###: R-id}}.

    Conservative by design (the file is prose, not a register table): only
    scope-defining lines are harvested - 'Touches:' lines, '**... scope:**'
    lines, lines that START with a REQ token (after optional 'Also here:'
    prefix and bold markers), pure number-continuation lines (', 051, 053 ...')
    and table rows whose first cell holds REQ tokens (the R1 SHOULD table).
    Prose like 'Deliberately not in R1: REQ-058 ...' is therefore NOT an edge.
    Enumeration lists that wrap mid-list are followed via a continuation
    state (open line ends with ',' or an unbalanced parenthesis); on such
    continuation lines only REQ tokens OUTSIDE parentheses are harvested, so
    asides like '(REQ-085 was listed here until ...)' stay out.
    First mention wins (a REQ lands in exactly one release).
    """
    path = ROOT / "RELEASES.md"
    if not path.exists():
        return {"releases": [], "edges": {}}
    text = path.read_text(encoding="utf-8")
    releases, edges = [], {}
    for m in re.finditer(r"(?ms)^## (R\d+(?:\.\d+)?)\s*-\s*(.+?)$(.*?)(?=^## |\Z)",
                         text):
        rid, title, body = m.group(1), m.group(2).strip(), m.group(3)
        releases.append({"id": rid, "title": short(title, 120)})
        cont = False
        for line in body.splitlines():
            s = line.strip()
            if not s:
                cont = False
                continue
            harvest = None
            trigger = False
            if s.startswith("|"):
                cells = [c.strip() for c in s.strip("|").split("|")]
                if cells and re.search(r"REQ-\d{3}", cells[0]):
                    harvest, trigger = cells[0], True
            else:
                sm = re.match(r"\*\*[^*]*\bscope:\*\*\s*(.*)$", s)
                t = sm.group(1) if sm else s.lstrip("* ")
                for pre in ("Touches:", "Also here:"):
                    if t.startswith(pre):
                        t = t[len(pre):].lstrip("* ")
                if re.match(r"REQ-\d{3}", t) or (
                        re.fullmatch(r"[\d.,\s]+", t) and re.search(r"\d{3}", t)):
                    harvest, trigger = t, True
            if trigger:
                # scope-defining line: ranges and bare-number continuations
                for req in expand_reqs(harvest):
                    edges.setdefault(req, rid)
            elif cont:
                # wrapped enumeration line: explicit REQ tokens only, and only
                # outside parentheses (prose asides like '(REQ-085 was listed
                # here until ...)' or OQ/DEC references must not become edges)
                aside = re.sub(r"\([^()]*\)", " ", s)
                for mm in re.finditer(r"REQ-(\d{3})((?:/\d{3})*)", aside):
                    edges.setdefault(f"REQ-{mm.group(1)}", rid)
                    for n in re.findall(r"\d{3}", mm.group(2)):
                        edges.setdefault(f"REQ-{n}", rid)
            cont = ((trigger or cont)
                    and (s.rstrip().endswith(",")
                         or s.count("(") != s.count(")")))
    return {"releases": releases, "edges": edges}


def scan_if_test_marker_files():
    """IF-### token -> set of test files carrying it (same scan scope as
    scan_if_test_markers; POSIX-style relative paths for stable output)."""
    found = {}
    for pattern in ("src/tests/**/*.py", "frontend/tests/**/*.ts"):
        for path in sorted(ROOT.glob(pattern)):
            if "__pycache__" in path.parts:
                continue
            rel = str(path.relative_to(ROOT)).replace("\\", "/")
            for iid in set(re.findall(r"IF-\d{3}",
                                      path.read_text(encoding="utf-8"))):
                found.setdefault(iid, set()).add(rel)
    return found


def _natkey(nid):
    return tuple(f"{int(p):06d}" if p.isdigit() else p
                 for p in re.split(r"(\d+)", nid))


def build_graph(reqs, decs, oqs, risks, chgs, cov, alloc, tc_rows, if_reg):
    nodes = {}          # id -> {'id', 'type', 'title'?}
    edges = {}          # (from, to, type) -> source ('+'-joined when several)

    def node(nid, ntype, title=None, excerpt=None):
        n = nodes.setdefault(nid, {"id": nid, "type": ntype})
        if title and "title" not in n:
            n["title"] = title
        if excerpt and "excerpt" not in n:
            n["excerpt"] = excerpt

    def implicit(nid):
        if nid not in nodes:
            node(nid, PREFIX_TYPE.get(nid.split("-")[0], "other"))

    def edge(frm, to, etype, source):
        if frm == to:
            return
        key = (frm, to, etype)
        if key in edges:
            if source not in edges[key].split("+"):
                edges[key] += "+" + source
        else:
            edges[key] = source

    for r in reqs:
        node(r["id"], "requirement", r["title"], r.get("excerpt"))
    for d in decs:
        node(d["id"], "decision", d["title"], d.get("excerpt"))
    for o in oqs:
        node(o["id"], "question", o["title"], o.get("excerpt"))
    for r in risks:
        node(r["id"], "risk", r["title"], r.get("excerpt"))
    for c in chgs:
        node(c["id"], "change", c["title"], c.get("excerpt"))
    for t in tc_rows:
        node(t["tc"], "test-case")
    for iid in if_reg["ifs"]:
        node(iid, "interface")

    # duplicate CHG numbers collapse into one node - surface that (S-5 style)
    chg_ids = [c["id"] for c in chgs]
    dupes = sorted({c for c in chg_ids if chg_ids.count(c) > 1})
    if dupes:
        print(f"WARN graph: duplicate CHG ids in CHANGELOG.md: "
              f"{', '.join(dupes)}", file=sys.stderr)

    # --- DEC markers: decides / amends / supersedes / closes / links
    body_rel = parse_dec_body_relations()
    superseded_by = {}
    for d in decs:
        m = re.fullmatch(r"superseded by (DEC-\d{3})", d["status"])
        if m:
            superseded_by[d["id"]] = m.group(1)
    for d in decs:
        for tok in extract_ids(d["links"]):
            implicit(tok)
            prefix = tok.split("-")[0]
            if prefix == "REQ":
                edge(d["id"], tok, "decides", "dec-links")
            elif prefix == "OQ":
                edge(tok, d["id"], "closes", "dec-links")
            elif prefix == "DEC":
                if superseded_by.get(tok) == d["id"] or (
                        tok in body_rel.get(d["id"], {}).get("supersedes", [])):
                    edge(d["id"], tok, "supersedes", "dec-links")
                elif tok in body_rel.get(d["id"], {}).get("amends", []):
                    edge(d["id"], tok, "amends", "dec-links")
                else:
                    edge(d["id"], tok, "links", "dec-links")
            else:
                edge(d["id"], tok, "links", "dec-links")

    # --- closes from the OQ status cell
    for oq, dlist in parse_oq_resolutions().items():
        for did in dlist:
            implicit(did)
            edge(oq, did, "closes", "oq-status")

    # --- covers: REQ -> concept section ('SC 3.4/3.5' splits into two edges)
    for rid, ref in cov.items():
        for sec in ref[3:].split("/"):
            sid = f"SC {sec}"
            node(sid, "section")
            edge(rid, sid, "covers", "coverage-table")

    # --- allocated_to: REQ -> SUB / IF
    for rid, a in alloc.items():
        for s in a["sub"]:
            implicit(s)
            edge(rid, s, "allocated_to", "allocation-table")
        for i in a["if"]:
            implicit(i)
            edge(rid, i, "allocated_to", "allocation-table")

    # --- tested_by: REQ -> TC (+ REQ -> crossed IF), IF -> test file (marker)
    for t in tc_rows:
        edge(t["req"], t["tc"], "tested_by", "tc-allocation")
        if t["if"] != "-":
            implicit(t["if"])
            edge(t["req"], t["if"], "tested_by", "tc-allocation")
    for iid, files in sorted(scan_if_test_marker_files().items()):
        implicit(iid)
        for f in sorted(files):
            node(f, "test-file")
            edge(iid, f, "tested_by", "test-marker-scan")

    # --- affects: CHG -> machine-readable IDs in 'Affected artifacts'
    for cid, ids in parse_chg_affects().items():
        for tok in ids:
            implicit(tok)
            edge(cid, tok, "affects", "changelog")

    # --- in_release: REQ -> release (conservative RELEASES.md parse)
    rel = parse_releases()
    for r in rel["releases"]:
        node(r["id"], "release", r["title"])
    for req, rid in rel["edges"].items():
        implicit(req)
        edge(req, rid, "in_release", "releases-md")

    # --- register entry excerpts for register-backed nodes without a
    # title-carrying parse above (TC register scenario, IF/SUB section bodies,
    # FR register bodies, M agenda/meeting bodies). Nodes without a register
    # home (sections, releases, test files, implicit IDs) get no excerpt.
    excerpts = {}
    for src in (parse_tc_register(), parse_sub_excerpts(),
                parse_fr_excerpts(), parse_agenda_item_excerpts(),
                if_reg.get("excerpts", {})):
        excerpts.update(src)
    for nid, ex in excerpts.items():
        if ex and nid in nodes:
            nodes[nid]["excerpt"] = ex

    # --- validator: edges to unknown register IDs are consistency warnings
    authoritative = ({r["id"] for r in reqs} | {d["id"] for d in decs} |
                     {o["id"] for o in oqs} | {r["id"] for r in risks} |
                     set(chg_ids) | {t["tc"] for t in tc_rows} |
                     set(if_reg["ifs"]) |
                     {s for a in alloc.values() for s in a["sub"]})
    dangling = {}
    for (frm, to, etype) in edges:
        for ep in (frm, to):
            if (ep.split("-")[0] in REGISTER_PREFIXES
                    and ep not in authoritative):
                dangling.setdefault(ep, []).append(f"{frm}->{to} ({etype})")
    for ep in sorted(dangling, key=_natkey):
        refs = ", ".join(dangling[ep][:3])
        more = f" +{len(dangling[ep]) - 3} more" if len(dangling[ep]) > 3 else ""
        print(f"WARN graph: edge to unknown ID {ep}: {refs}{more}",
              file=sys.stderr)

    node_list = sorted(nodes.values(), key=lambda n: _natkey(n["id"]))
    edge_list = [{"from": f, "to": t, "type": ty, "source": src}
                 for (f, t, ty), src in sorted(
                     edges.items(), key=lambda kv: (_natkey(kv[0][0]), kv[0][2],
                                                    _natkey(kv[0][1])))]
    return {"_generated":
            "GENERATED by tools/build_index.py - do not edit by hand - "
            "regenerate: python tools/build_index.py from the project root",
            "nodes": node_list, "edges": edge_list}


def main():
    reqs = parse_requirements()
    decs = parse_decisions()
    oqs = parse_open_questions()
    risks = parse_risks()
    chgs = parse_changelog()
    cov = parse_coverage()
    alloc = parse_allocations()
    tc_rows = parse_tc_allocations()

    if_reg = parse_if_register()

    (ROOT / "INDEX.md").write_text(build_index(reqs, decs, oqs, risks, chgs, tc_rows),
                                   encoding="utf-8")
    (ROOT / "TRACEABILITY.md").write_text(
        build_traceability(reqs, cov, alloc, tc_rows, if_reg),
        encoding="utf-8")

    graph = build_graph(reqs, decs, oqs, risks, chgs, cov, alloc, tc_rows,
                        if_reg)
    (ROOT / "graph.json").write_text(
        json.dumps(graph, indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8")
    type_counts = {}
    for e in graph["edges"]:
        type_counts[e["type"]] = type_counts.get(e["type"], 0) + 1
    n_excerpt = sum(1 for n in graph["nodes"] if n.get("excerpt"))
    print(f"graph: {len(graph['nodes'])} nodes | {len(graph['edges'])} edges "
          f"({', '.join(f'{t} {n}' for t, n in sorted(type_counts.items()))}) | "
          f"excerpts {n_excerpt}")

    gaps = [i for i in if_reg["ifs"]
            if i not in scan_if_test_markers() and i not in if_reg["pinned"]]
    print(f"IF {len(if_reg['ifs'])} (pinned {len(if_reg['pinned'])}) | "
          f"no integration test: {', '.join(gaps) if gaps else 'none'}")

    print(f"REQ {len(reqs)} | DEC {len(decs)} | OQ {len(oqs)} | RISK {len(risks)} "
          f"| CHG {len(chgs)} | covered {len(cov)} | allocated {len(alloc)}")
    missing = [r["id"] for r in reqs if r["id"] not in cov]
    print(f"uncovered (status open): {', '.join(missing) if missing else 'none'}")


if __name__ == "__main__":
    main()
