def build_index(reqs, decs, oqs, risks, chgs, tc_rows):
    lines = [
        "# Index",
        "",
        GEN,
        "Regenerate: `python tools/build_index.py` from the project root.",
        "One line per entity; read this before opening any register in full.",
        "",
        f"Counts: {len(reqs)} REQ | {len(decs)} DEC | {len(oqs)} OQ "
        f"({sum(1 for o in oqs if 'resolved' in o['status'].lower())} resolved) | "
        f"{len(risks)} RISK | {len(chgs)} CHG entries",
        "",
        "## Requirements (REQ -> requirements.md)",
        "",
    ]
    for r in reqs:
        lines.append(f"- {r['id']} | {r['prio']} | {r['title']}")
    lines += ["", "## Decisions (DEC -> DECISIONS.md)", ""]
    for d in decs:
        link = f" | links: {d['links']}" if d["links"] else ""
        lines.append(f"- {d['id']} | {d['status']} | {d['date']} | {d['title']}{link}")
    lines += ["", "## Open questions (OQ -> OPEN-QUESTIONS.md)", ""]
    for o in oqs:
        lines.append(f"- {o['id']} | {o['status']} | {o['title']}")
    lines += ["", "## Risks (RISK -> RISKS.md)", ""]
    for r in risks:
        lines.append(f"- {r['id']} | {r['status']} | {r['title']}")
    lines += ["", "## Change log (CHG -> CHANGELOG.md, newest first)", ""]
    for c in chgs:
        lines.append(f"- {c['id']} | {c['date']} | {c['title']}")
    lines += ["", "## Test cases (TC -> 05-module-specification/test-cases.md)", ""]
    for t in tc_rows:
        lines.append(f"- {t['tc']} | {t['req']} | {t['sub']}")
    lines.append("")
    return "\n".join(lines)


def build_traceability(reqs, cov, alloc, tc_rows, if_reg):
    tc_by_req = {}
    for t in tc_rows:
        tc_by_req.setdefault(t["req"], [])
        if t["tc"] not in tc_by_req[t["req"]]:
            tc_by_req[t["req"]].append(t["tc"])
    req_ids = {r["id"] for r in reqs}
    alloc_pairs = {(rid, s) for rid, a in alloc.items() for s in a["sub"]}
    lines = [
        "# Traceability Matrix",
        "",
        GEN,
        "Regenerate: `python tools/build_index.py` from the project root.",
        "The Solution column is a projection of the coverage table in",
        "`02-solution-concept/solution-concept.md` (section 4); the ARC/IF and SUB",
        "columns are a projection of the allocation table in",
        "`04-architecture/architecture.md` (Allocation section); the Test case (TC)",
        "column is a projection of the TC allocation table in",
        "`05-module-specification/test-cases.md` - edit them there, then rebuild.",
        "",
        "Links each requirement through the whole V so nothing is unbuilt or unverified.",
        "",
        "| REQ | Solution | Architecture (ARC/IF) | Submodule (SUB) | Test case (TC) | Validation test | Status |",
        "|-----|----------|-----------------------|-----------------|----------------|-----------------|--------|",
    ]
    for r in reqs:
        ref = cov.get(r["id"], "")
        a = alloc.get(r["id"], {"sub": [], "if": []})
        sub = ", ".join(a["sub"])
        arc = ", ".join(a["if"])
        tcs = ", ".join(tc_by_req.get(r["id"], []))
        # empty cells render as "| |" so a missing allocation or TC table leaves
        # the row byte-identical to the pre-phase-04 format
        arc_cell = f" {arc} " if arc else " "
        sub_cell = f" {sub} " if sub else " "
        tc_cell = f" {tcs} " if tcs else " "
        if tcs:
            status = "specced"
        elif sub:
            status = "allocated"
        elif ref:
            status = "concept"
        else:
            status = "open"
        lines.append(
            f"| {r['id']} | {ref} |{arc_cell}|{sub_cell}|{tc_cell}| | {status} |")
    no_sub = [r["id"] for r in reqs if r["id"] in cov and r["id"] not in alloc]
    no_tc = [rid for rid in alloc if rid not in tc_by_req]
    orphans = [f"{t['tc']} ({t['req']}/{t['sub']})" for t in tc_rows
               if t["req"] not in req_ids or (t["req"], t["sub"]) not in alloc_pairs]
    lines += [
        "",
        "## Coverage checks (auto-filled)",
        "- Requirements with no allocated submodule: "
        f"{', '.join(no_sub) if no_sub else 'none'}",
        "- Requirements with no test case: "
        f"{', '.join(no_tc) if no_tc else 'none'}",
        "- Test cases with no parent requirement (orphans): "
        f"{', '.join(orphans) if orphans else 'none'}",
    ]
    if not if_reg["ifs"]:
        lines.append("- Interfaces (IF-###) with no integration test: "
                     "(interface register not found - not computed)")
    else:
        tested = scan_if_test_markers()
        gaps = [i for i in if_reg["ifs"]
                if i not in tested and i not in if_reg["pinned"]]
        lines.append("- Interfaces (IF-###) with no integration test: "
                     f"{', '.join(gaps) if gaps else 'none'}")
        lines.append("- Interfaces (IF-###) boundary-pinned "
                     "(post-R1/post-MVP, not tested): "
                     f"{', '.join(if_reg['pinned']) if if_reg['pinned'] else 'none'}")
    lines.append("")
    return "\n".join(lines)


