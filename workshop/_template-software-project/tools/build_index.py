"""Build INDEX.md and TRACEABILITY.md from the project registers.

Reads (never edits): requirements.md, DECISIONS.md, OPEN-QUESTIONS.md, RISKS.md,
CHANGELOG.md, 02-solution-concept/solution-concept.md (coverage table),
04-architecture/architecture.md (allocation table, optional - written in phase 04),
05-module-specification/test-cases.md (TC allocation table, optional - written in
phase 05).

Writes (fully generated): INDEX.md, TRACEABILITY.md, graph.json (typed nodes +
typed edges for tools/query_graph.py; register-backed nodes also carry an
'excerpt' - the entry body, whitespace-normalized, capped at 800 chars; the
validator warns on edges pointing at nonexistent register IDs).

Run from the project root:  python tools/build_index.py

Robustness contract (see workshop/agent-navigation-supplement.md, Addition A):
- requirements: table rows `| REQ-### | ... | <priority cell> |` - priority = first word
  of the last cell.
- DECISIONS.md: one marker comment per record, directly under the heading:
  `<!-- DEC-### | <status> | links: ID, ID ... -->`
- OPEN-QUESTIONS.md: table rows `| OQ-### | ... | <status cell> |`.
- RISKS.md: table rows `| RISK-### | ... | <status cell> |`.
- CHANGELOG.md: headings `## [CHG-###] YYYY-MM-DD - <title>`.
- Coverage: rows of the section-4 table in solution-concept.md; the first cell may use
  ranges (REQ-001..008), continuations (REQ-010, 082) and shorthand (REQ-088..090).
- Allocation (optional): the first table under a heading containing "Allocation"
  (any level, case-insensitive) in 04-architecture/architecture.md; rows
  `| REQ-### | SUB-### | IF-### |`, several rows per REQ allowed, `-` in the IF
  cell means submodule-internal (no interface). Whitespace is tolerated, invalid
  rows are skipped (never a crash); a missing file, section or table leaves the
  ARC/IF and SUB columns empty.
- TC allocation (optional): the first table under a heading containing "TC
  allocation" (any level, case-insensitive) in
  05-module-specification/test-cases.md; rows `| TC-### | REQ-### | SUB-### |
  IF-### |`, several rows per TC allowed, `-` in the IF cell allowed. IDs only.
  Whitespace is tolerated, invalid rows are skipped (never a crash); a missing
  file, section or table leaves the TC column empty.
- IF integration coverage (optional, phase 07, finding S-5): the interface
  inventory comes from architecture.md section 3 headings
  `### IF-### - <title>`; a title carrying "(post-R1 boundary)" or
  "(post-MVP boundary)" marks the contract as boundary-pinned (explicitly
  not tested). A test marker is the IF-### token appearing in any test
  source file (`src/tests/**/*.py`, `frontend/tests/**/*.ts`) - a
  tripwire, not a proof: the authoritative per-IF crossing test is named
  in reviews/2026-08-22-phase-07-unit1-review.md. A missing file or section leaves both
  lines with an explicit note instead of failing the build.

Linter/type-checker policy: this is a small, single-purpose utility with the
documented robustness contract above. Strict type-annotation and style warnings
are intentionally suppressed file-wide (comments below) so the workspace
diagnostic counter stays meaningful for real code (phase 04+).
"""
